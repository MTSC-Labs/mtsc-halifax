#!/usr/bin/env node

/**
 * Generates the admin seed SQL for MTSC Halifax D1 database.
 *
 * Usage:
 *   node scripts/seed-admin.js
 *
 * Outputs:
 *   - Prints INSERT SQL to stdout
 *   - Writes migrations/0002_seed_admin.sql
 */

import bcrypt from 'bcryptjs';
import { writeFileSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));

const ADMIN_EMAIL = 'mtsc@admin.com';
const ADMIN_PASSWORD = 'AboutmostWin58';
const SALT_ROUNDS = 10;

async function main() {
  const hash = await bcrypt.hash(ADMIN_PASSWORD, SALT_ROUNDS);

  const sql = `-- MTSC Halifax Admin Seed
-- Generated by scripts/seed-admin.js
-- Default admin: ${ADMIN_EMAIL}

INSERT OR IGNORE INTO admins (email, password_hash, role)
VALUES ('${ADMIN_EMAIL}', '${hash}', 'admin');
`;

  // Print to stdout
  console.log(sql);

  // Write seed migration file
  const outPath = resolve(__dirname, '..', 'migrations', '0002_seed_admin.sql');
  writeFileSync(outPath, sql, 'utf-8');
  console.log(`\nSeed file written to: ${outPath}`);
}

main().catch((err) => {
  console.error('Error generating seed:', err);
  process.exit(1);
});
