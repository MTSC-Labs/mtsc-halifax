#!/usr/bin/env node
/**
 * Generates the admin seed SQL for MTSC Halifax D1 database.
 * Uses PBKDF2-SHA256 (Web Crypto compatible) instead of bcrypt.
 * Usage: node scripts/seed-admin.js
 * Default admin: mtsc@admin.com / AboutmostWin58
 */
import { webcrypto } from 'crypto';
import { writeFileSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const ITERATIONS = 100000;
const HASH_BYTES = 32;
const SALT_BYTES = 16;

function toBase64(buffer) {
  return Buffer.from(buffer).toString('base64');
}

async function hashPassword(password) {
  const salt = webcrypto.getRandomValues(new Uint8Array(SALT_BYTES));
  const key = await webcrypto.subtle.importKey(
    'raw',
    new TextEncoder().encode(password),
    'PBKDF2',
    false,
    ['deriveBits']
  );
  const hash = await webcrypto.subtle.deriveBits(
    { name: 'PBKDF2', hash: 'SHA-256', salt, iterations: ITERATIONS },
    key,
    HASH_BYTES * 8
  );
  return `$pbkdf2$${ITERATIONS}$${toBase64(salt)}$${toBase64(hash)}`;
}

const email = process.argv[2] || 'mtsc@admin.com';
const password = process.argv[3] || 'AboutmostWin58';

const hash = await hashPassword(password);
console.log(`Email: ${email}`);
console.log(`Hash:  ${hash}`);

const sql = `-- MTSC Halifax Admin Seed (PBKDF2-SHA256)
-- Generated by scripts/seed-admin.js
-- Default admin: ${email}

DELETE FROM admins WHERE email = '${email}';
INSERT INTO admins (email, password_hash, role)
VALUES ('${email}', '${hash}', 'admin');
`;

const outPath = resolve(__dirname, '../migrations/0002_seed_admin.sql');
writeFileSync(outPath, sql);
console.log(`\nSeed SQL written to: ${outPath}`);
